def generate_csv_report(tor_ips, non_tor_ips):
    """Generates a CSV report with one row per analyzed IP."""
    with open(CSV_REPORT_FILE, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["ip", "is_tor_exit_node"])
        for ip in tor_ips:
            writer.writerow([ip, True])
        for ip in non_tor_ips:
            writer.writerow([ip, False])
        f.flush()
        os.fsync(f.fileno())


def main(args):
    enable_ansi_colors()
    setup_logging(args.log)
    print_logo()
    logger.info("Run started")

    try:
        ip_list, invalid_lines = load_ip_list(args.input)
    except (FileNotFoundError, ValueError) as exc:
        logger.error("Failed to load IP list: %s", exc)
        print(RED + BRIGHT + f"[ERROR] {exc}" + RESET)
        sys.exit(1)

    if invalid_lines:
        details = f" (see {LOG_FILE} for details)" if args.log else " (rerun with --log for details)"
        print(YELLOW + f"[WARNING] Ignored {len(invalid_lines)} invalid entr"
              f"{'y' if len(invalid_lines) == 1 else 'ies'} in {args.input}"
              f"{details}." + RESET)

    try:
        tor_exit_nodes = get_tor_exit_nodes()
    except TorListUnavailableError as exc:
        logger.error("Could not download TOR exit node list: %s", exc)
        print(RED + BRIGHT + "[ERROR] Could not download the TOR exit node list "
              f"({exc}). Aborting to avoid producing a misleading report." + RESET)
        sys.exit(1)

    tor_ips = []
    non_tor_ips = []

    for ip in ip_list:
        if check_ip(ip, tor_exit_nodes):
            tor_ips.append(ip)
        else:
            non_tor_ips.append(ip)

    if tor_ips:
        print(YELLOW + BRIGHT + "The following IPs are TOR exit nodes:")
        for ip in tor_ips:
            print(RED + BRIGHT + f"{ip}")
        print(RESET)
    else:
        print(GREEN + BRIGHT + "No IPs found that are TOR exit nodes." + RESET)

    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    if args.no_report:
        logger.info("Skipping report generation (--no-report)")
    else:
        try:
            generate_html_report(tor_ips, non_tor_ips, invalid_lines, len(ip_list), generated_at)
            generate_csv_report(tor_ips, non_tor_ips)
        except OSError as exc:
            logger.error("Failed to write report files: %s", exc)
            print(RED + BRIGHT + f"[ERROR] Failed to write report files: {exc}" + RESET)
            sys.exit(1)

    logger.info(
        "Run finished: %d analyzed, %d TOR nodes, %d invalid entries",
        len(ip_list), len(tor_ips), len(invalid_lines),
    )
    if args.no_report:
        print(CYAN + BRIGHT + "[INFO] Report generation skipped (--no-report)." + RESET)
    else:
        print(CYAN + BRIGHT + "[INFO] Reports generated: " + LIGHTBLUE +
              f"{HTML_REPORT_FILE}, {CSV_REPORT_FILE}" + RESET)


if __name__ == "__main__":
    cli_args = parse_args()
    try:
        main(cli_args)
    except Exception:
        logger.exception("Unexpected error")
        if cli_args.log:
            print(RED + BRIGHT + f"[ERROR] An unexpected error occurred. Check {LOG_FILE} for details." + RESET)
        else:
            traceback.print_exc()
            print(RED + BRIGHT + "[ERROR] An unexpected error occurred (see traceback above)." + RESET)
        sys.exit(1)
