def parse_args():
    parser = argparse.ArgumentParser(
        description="Check a list of IPs against the official TOR exit node list."
    )
    parser.add_argument(
        "-i", "--input",
        default=IP_LIST_FILE,
        metavar="FILE",
        help=f"Path to the file with one IP per line (default: {IP_LIST_FILE}).",
    )
    parser.add_argument(
        "--log",
        action="store_true",
        help=f"Write a detailed run log to {LOG_FILE} (disabled by default).",
    )
    parser.add_argument(
        "--no-report",
        action="store_true",
        help=f"Skip generating {HTML_REPORT_FILE} and {CSV_REPORT_FILE} (both are generated by default).",
    )
    return parser.parse_args()


def setup_logging(enable_log_file):
    """Configures file logging so runs can be audited later, only if requested."""
    logger.setLevel(logging.INFO)
    if enable_log_file:
        handler = logging.FileHandler(LOG_FILE, encoding="utf-8")
        handler.setFormatter(logging.Formatter("%(asctime)s [%(levelname)s] %(message)s"))
        logger.addHandler(handler)
    else:
        logger.addHandler(logging.NullHandler())
    logger.propagate = False


def enable_ansi_colors():
    """Enables ANSI escape sequence processing on Windows consoles."""
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except AttributeError:
        pass
    if sys.platform == "win32":
        kernel32 = ctypes.windll.kernel32
        handle = kernel32.GetStdHandle(-11)  # STD_OUTPUT_HANDLE
        mode = ctypes.c_uint32()
        if kernel32.GetConsoleMode(handle, ctypes.byref(mode)):
            kernel32.SetConsoleMode(handle, mode.value | 0x0004)  # ENABLE_VIRTUAL_TERMINAL_PROCESSING


