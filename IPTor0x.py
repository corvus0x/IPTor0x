class TorListUnavailableError(Exception):
    """Raised when the official TOR exit node list cannot be downloaded."""


def get_tor_exit_nodes():
    """Downloads the list of TOR exit nodes from the official site."""
    try:
        with urllib.request.urlopen(TOR_EXIT_LIST_URL, timeout=10) as response:
            if response.status != 200:
                raise TorListUnavailableError(f"Unexpected HTTP status {response.status}")
            return set(response.read().decode("utf-8").splitlines())
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise TorListUnavailableError(str(exc)) from exc


def load_ip_list(file_path):
    """Loads and validates the list of IPs from a file.

    Returns a tuple (valid_ips, invalid_lines). Invalid or duplicate
    lines are skipped (and logged) rather than crashing the run.
    """
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            raw_lines = [line.strip() for line in f if line.strip()]
    except FileNotFoundError as exc:
        raise FileNotFoundError(
            f"Input file '{file_path}' was not found. Create it with one IP per line."
        ) from exc

    valid_ips = []
    invalid_lines = []
    seen = set()
    for line in raw_lines:
        try:
            ipaddress.ip_address(line)
        except ValueError:
            invalid_lines.append(line)
            logger.warning("Skipping invalid IP entry: %r", line)
            continue
        if line in seen:
            logger.info("Skipping duplicate IP entry: %s", line)
            continue
        seen.add(line)
        valid_ips.append(line)

    if not valid_ips:
        raise ValueError(f"No valid IP addresses found in '{file_path}'.")

    return valid_ips, invalid_lines


def check_ip(ip, tor_exit_nodes):
    """Checks if an IP is in the TOR exit node list."""
    return ip if ip in tor_exit_nodes else None


